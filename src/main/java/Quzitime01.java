public class Quzitime01 {
    public static void main(String[] args) {

        for (int i = 0; i < 4; i++) {


            for (int z = 0; z <= i; z++) {
                System.out.print("*");
            }
            System.out.println();
        }

        for (int i = 1; i >= 0; i--) {


            for (int z = 0; z <= i; z++) {
                System.out.print("*");
            }
            System.out.println();
        }
    }
}
